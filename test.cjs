const fs = require('node:fs');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const html = fs.readFileSync('index.html', 'utf8');
const css = fs.readFileSync('styles.css', 'utf8');
for (const id of ['home','about','interests','projects','contact']) assert(html.includes(`id="${id}"`));
for (const match of html.matchAll(/href="#([^"]+)"/g)) assert(html.includes(`id="${match[1]}"`));
for (const file of ['styles.css','script.js']) assert(fs.existsSync(file));
assert.equal((html.match(/class="project"/g)||[]).length, 3);
assert(css.includes('max-width:600px') && css.includes('max-width:900px'));
assert(css.includes('prefers-reduced-motion'));
const handlers = {};
let expanded = 'false'; let opened = false; let closed = false;
const menu = {setAttribute: (_,value) => expanded = value, addEventListener: (_,fn) => handlers.menu = fn};
const nav = {classList: {toggle: () => opened = !opened, remove: () => opened = false}, querySelectorAll: () => [],};
const dialog = {addEventListener: () => {}, close: () => closed = true};
const year = {};
const document = {querySelector: s => ({'.menu':menu,'nav':nav,'#project-dialog':dialog,'#year':year}[s]), querySelectorAll: s => s === '.close, .close-bottom' ? [{addEventListener: (_,fn) => handlers.close = fn}] : [], addEventListener: (_,fn) => handlers.key = fn};
vm.runInNewContext(fs.readFileSync('script.js','utf8'), {document, window:{}, Date});
handlers.menu(); assert.equal(expanded,'true'); assert(opened);
handlers.key({key:'Escape'}); assert.equal(expanded,'false'); assert(!opened);
handlers.close(); assert(closed);
assert.equal(year.textContent, new Date().getFullYear());
console.log('PASS: page sections, anchors, assets, project count, responsive rules, reduced motion, menu toggle, Escape, dialog close, year');
